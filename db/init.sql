-- =============================================================================
-- db/init.sql
-- -----------------------------------------------------------------------------
-- PURPOSE:
--   Builds the database tables that REPLACE server/users.txt.
--
--   Docker runs this file automatically, but only the FIRST time the database
--   container is created (when the data volume is empty). If you change this
--   file later, reset the database so it runs again:
--       docker compose down -v      (WARNING: deletes all saved data)
--       docker compose up -d
--
--   users.txt kept everything about a person in one JSON object. Here it is
--   split into two tables so login data and profile data are kept apart:
--
--     users         -> account/login info  (id, email, password hash)
--     user_details  -> what the Details page collects
--                      (name, age, hobbies, bedtime, cleanliness, pets)
-- =============================================================================


-- -----------------------------------------------------------------------------
-- TABLE: users
-- One row per account. Created by POST /api/signup, read by POST /api/login.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    -- A random unique ID (same UUID format users.txt used), generated by
    -- PostgreSQL automatically so the server never has to make one.
    id             UUID         PRIMARY KEY DEFAULT gen_random_uuid(),

    -- UNIQUE means two accounts can never share an email. The database
    -- enforces this itself, even if two people sign up at the same moment.
    -- PostgreSQL also builds an index on a UNIQUE column automatically, so
    -- finding a user by email at login is fast no matter how many users exist.
    -- (The index type is a B-tree, PostgreSQL's default.)
    email          VARCHAR(255) NOT NULL UNIQUE,

    -- The bcrypt hash of the password. The real password is NEVER stored.
    password_hash  TEXT         NOT NULL,

    -- When the account was created; filled in automatically.
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


-- -----------------------------------------------------------------------------
-- TABLE: user_details
-- One row per user, holding what they entered on the Details page.
-- A brand-new account has NO row here yet; the row is created the first time
-- the user saves the Details form (PUT /api/details/:userId).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_details (
    -- Links these details to their account in the users table.
    -- Making it the PRIMARY KEY guarantees each user has at most ONE row.
    -- ON DELETE CASCADE: deleting a user automatically deletes their details.
    user_id      UUID         PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,

    name         VARCHAR(100) NOT NULL,

    -- Stored as a real number (not text) so you can later search by age range.
    -- The CHECK rule stops bad values from ever being saved.
    age          SMALLINT     NOT NULL CHECK (age BETWEEN 18 AND 120),

    hobbies      VARCHAR(500) NOT NULL DEFAULT '',

    -- Stored as a real time of day (e.g. 23:00). NULL means "not given".
    bedtime      TIME,

    -- Only the options offered on the Details page are allowed.
    cleanliness  VARCHAR(20)  NOT NULL
                 CHECK (cleanliness IN ('relaxed', 'moderate', 'very-clean')),
    pets         VARCHAR(10)  NOT NULL
                 CHECK (pets IN ('yes', 'no', 'depends')),

    -- When the details were last saved; the server updates this on each save.
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);


-- -----------------------------------------------------------------------------
-- INDEXES
-- An index is like the index at the back of a book: it lets PostgreSQL jump
-- straight to matching rows instead of reading the whole table.
--
